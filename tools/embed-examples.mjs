// Examples kept as real files (examples/<name>/) are copied, as text, into src/examples.generated.ts,
// which the page and the tests import. Run by `npm test` and `npm run build`; the result is committed.
//
// A folder holds one grammar (*.langium), optionally a validator (*validator.ts) and a generator
// (generator.ts), and programs (any other file), listed in the order given below.
import fs from 'node:fs';
import path from 'node:path';

const EXAMPLES = [
    { constant: 'CHESS_FULL_GAME', name: 'Chess (full game)', folder: 'examples/chess-full-game', programs: ['opera.chess', 'special-moves.chess', 'illegal.chess'] },
];

const read = file => fs.readFileSync(file, 'utf8');
let out = '// Generated by tools/embed-examples.mjs from the files of examples/: do not edit.\n';
out += "import type { Example } from './examples.ts';\n";
for (const ex of EXAMPLES) {
    const files = fs.readdirSync(ex.folder);
    const one = test => { const f = files.find(test); return f ? read(path.join(ex.folder, f)) : undefined; };
    const example = {
        name: ex.name,
        grammar: one(f => f.endsWith('.langium')),
        programs: ex.programs.map(name => ({ name, text: read(path.join(ex.folder, name)) })),
        validator: one(f => f.endsWith('validator.ts')),
        generator: one(f => f === 'generator.ts'),
    };
    out += `\nexport const ${ex.constant}: Example = ${JSON.stringify(example, null, 4)};\n`;
}
const target = 'src/examples.generated.ts';
if (!fs.existsSync(target) || read(target) !== out) fs.writeFileSync(target, out);
